/**
 * 按 id 解析模板：先查内置模板，再查设置中的自定义模板；
 * 都找不到（如自定义模板已被删除）时回退到默认内置模板，保证生成管线不报错
 */
export function resolveTemplate(templateId: string): MeetingTemplate {
  const builtin = MEETING_TEMPLATES.find((t) => t.id === templateId)
  if (builtin) return builtin
  const custom = useSettingStore
    .getState()
    .customMeetingTemplates.find((t) => t.id === templateId)
  if (custom) {
    return { id: custom.id, name: custom.name, description: '', prompt: custom.prompt }
  }
  return MEETING_TEMPLATES[0]
}
